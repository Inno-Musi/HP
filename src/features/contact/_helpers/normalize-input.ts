// 任意項目の書式ゆれを、保存前に吸収する。
//
// 背景（2026-08-13 のGA4実測）: 28日で /ja/contact に49ユーザーが到達し、
// 11人がフォーム入力を開始したのに、完了は0だった。
// フォームの必須は4項目まで緩和済みだが、「任意」と表示している電話番号とカタカナには
// 厳格な書式検証が残っていて、書式が合わないと送信が止まっていた。
// しかも検証はServer Action側にしか無いため、ユーザーは送信を押して往復してからでないと
// 気づけない。
//
// 方針: **任意項目では送信を止めない。** 直せる表記ゆれはここで正規化し、
// 直せないものはそのまま受け入れる（書式判定は行わない）。
// 正規化した値が後段（メール本文・Slack通知）へ渡るので、保存されるデータはむしろ揃う。

/** 全角数字を半角へ */
const toHalfWidthDigits = (value: string) =>
  value.replace(/[０-９]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0))

/**
 * 電話番号: 全角数字を半角にし、ハイフン・空白・括弧・ドットを落とす。
 * 「03-1234-5678」「090 1234 5678」「(03)1234-5678」「０９０…」いずれも数字列になる。
 * 国番号の + は残す（+81 と 81 を区別できなくなるため）。
 */
export const normalizePhoneNumber = (value: unknown) =>
  typeof value === 'string'
    ? toHalfWidthDigits(value)
        .replace(/＋/g, '+')
        .replace(/[-‐‑‒–—―ー－\s()（）.]/g, '')
    : value

const HALF_WIDTH_KANA: Record<string, string> = {
  ｦ: 'ヲ', ｧ: 'ァ', ｨ: 'ィ', ｩ: 'ゥ', ｪ: 'ェ', ｫ: 'ォ', ｬ: 'ャ', ｭ: 'ュ', ｮ: 'ョ', ｯ: 'ッ',
  ｰ: 'ー', ｱ: 'ア', ｲ: 'イ', ｳ: 'ウ', ｴ: 'エ', ｵ: 'オ', ｶ: 'カ', ｷ: 'キ', ｸ: 'ク', ｹ: 'ケ',
  ｺ: 'コ', ｻ: 'サ', ｼ: 'シ', ｽ: 'ス', ｾ: 'セ', ｿ: 'ソ', ﾀ: 'タ', ﾁ: 'チ', ﾂ: 'ツ', ﾃ: 'テ',
  ﾄ: 'ト', ﾅ: 'ナ', ﾆ: 'ニ', ﾇ: 'ヌ', ﾈ: 'ネ', ﾉ: 'ノ', ﾊ: 'ハ', ﾋ: 'ヒ', ﾌ: 'フ', ﾍ: 'ヘ',
  ﾎ: 'ホ', ﾏ: 'マ', ﾐ: 'ミ', ﾑ: 'ム', ﾒ: 'メ', ﾓ: 'モ', ﾔ: 'ヤ', ﾕ: 'ユ', ﾖ: 'ヨ', ﾗ: 'ラ',
  ﾘ: 'リ', ﾙ: 'ル', ﾚ: 'レ', ﾛ: 'ロ', ﾜ: 'ワ', ﾝ: 'ン',
}

/**
 * ふりがな: 空白を落とし、半角カナと濁点・半濁点を全角へ、ひらがなをカタカナへ寄せる。
 * 「やまだ」「ヤマ ダ」「ﾔﾏﾀﾞ」いずれも「ヤマダ」になる。
 * 寄せられないもの（漢字など）はそのまま通す＝送信は止めない。
 */
export const normalizeKana = (value: unknown) => {
  if (typeof value !== 'string') return value
  return value
    .replace(/\s+/g, '')
    .replace(/([ｦ-ﾝ])([ﾞﾟ]?)/g, (_, base: string, mark: string) => {
      const full = HALF_WIDTH_KANA[base] ?? base
      if (!mark) return full
      // 濁点・半濁点は合成用の全角記号に置き換えて正規化で1文字にまとめる
      return (full + (mark === 'ﾞ' ? '゙' : '゚')).normalize('NFC')
    })
    .replace(/[ぁ-ゖ]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60))
}
